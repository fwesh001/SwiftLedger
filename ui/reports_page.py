    def _generate_member_pdf(self) -> None:
        if not self._validate_scope("member", for_export=True):
            return

        staff = self.search_member_widget.get_query()
        if not staff:
            QMessageBox.warning(self, "Input Required", "Enter a staff number or name.")
            return

        if not self._validate_date_range():
            return

        pdf, member = self._build_member_pdf(staff)
        if pdf is None or member is None:
            return

        default_dir = get_export_path("Report page", "Members statement (pdf)", member.get("full_name"), staff)
        path, _ = QFileDialog.getSaveFileName(
            self, "Save Member Statement",
            str(default_dir / f"SwiftLedger_Statement_{staff}.pdf"), "PDF Files (*.pdf)",
        )
        if not path:
            return

        if not self._write_pdf_to_path(pdf, path):
            QMessageBox.warning(
                self,
                "Export Error",
                "Unable to save the PDF. If the file is open, close it and try again.",
            )
            return

        log_event("Admin", "Reports",
                  f"Member statement exported for {member['full_name']} ({staff})",
                  "Success", self.db_path)
        QMessageBox.information(self, "Exported", f"Statement saved to:\n{path}")

